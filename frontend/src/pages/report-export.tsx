// Download centre for one stored scan. Server artifacts (CBOM, SARIF) are
// fetched as bytes and saved exactly as produced; local exports (JSON, CSV) are
// serialized from the same stored scan. A failed request never leaves a file
// behind and never reports success.
import { useEffect, useState } from 'react'
import { Link, useParams } from 'react-router-dom'
import { Download, FileJson, FileSearch, ShieldCheck } from 'lucide-react'
import { Panel } from '@/components/ui/panel'
import { Badge } from '@/components/ui/badge'
import { Button } from '@/components/ui/button'
import { PageHeader } from '@/components/ui/page-header'
import { EmptyState } from '@/components/ui/empty-state'
import { apiDownload, api, ApiError, type ScanDetail } from '@/lib/api'
import { formatTimestamp } from '@/lib/utils'

type FormatId = 'cbom' | 'sarif' | 'json' | 'csv'

interface FormatSpec {
  id: FormatId
  label: string
  detail: string
  filename: (scanId: number) => string
  source: 'server' | 'local'
  note: string
}

const FORMATS: FormatSpec[] = [
  {
    id: 'cbom',
    label: 'CBOM',
    detail: 'CycloneDX 1.7 JSON',
    filename: (id) => `piquachu-cbom-${id}.json`,
    source: 'server',
    note: 'Generated by the API from the stored scan. Inventory completeness is not claimed.',
  },
  {
    id: 'sarif',
    label: 'SARIF',
    detail: '2.1.0 log',
    filename: (id) => `piquachu-scan-${id}.sarif`,
    source: 'server',
    note: 'The API validates this document against the SARIF schema before returning it.',
  },
  {
    id: 'json',
    label: 'Scan JSON',
    detail: 'findings, matrix, plans',
    filename: (id) => `piquachu-scan-${id}.json`,
    source: 'local',
    note: 'Serialized in the browser from the same stored scan the page displays.',
  },
  {
    id: 'csv',
    label: 'Findings CSV',
    detail: 'one row per finding',
    filename: (id) => `piquachu-findings-${id}.csv`,
    source: 'local',
    note: 'UTF-8 CSV with quoted cells. No source snippets are included.',
  },
]

function csvCell(value: unknown): string {
  if (value === null || value === undefined) return ''
  const text = String(value)
  return /[",\n\r]/.test(text) ? `"${text.replace(/"/g, '""')}"` : text
}

function findingsToCsv(detail: ScanDetail): string {
  const header = 'rule_id,severity,verdict,standard,category,algorithm,file,line'
  const rows = detail.findings.map((finding) =>
    [
      finding.rule_id ?? finding.vulnerability,
      finding.severity,
      finding.verdict,
      finding.nist_standard,
      finding.category,
      finding.algorithm ?? finding.target_algorithm,
      finding.file,
      finding.line ?? finding.line_start,
    ]
      .map(csvCell)
      .join(','),
  )
  return [header, ...rows].join('\n')
}

function saveBlob(filename: string, blob: Blob): void {
  const url = URL.createObjectURL(blob)
  const anchor = document.createElement('a')
  anchor.href = url
  anchor.download = filename
  document.body.appendChild(anchor)
  anchor.click()
  document.body.removeChild(anchor)
  URL.revokeObjectURL(url)
}

function useScan(scanId: number | undefined) {
  const [state, setState] = useState<'loading' | 'ready' | 'notfound' | 'error'>(
    scanId ? 'loading' : 'notfound',
  )
  const [detail, setDetail] = useState<ScanDetail | null>(null)
  const [error, setError] = useState<string | null>(null)

  useEffect(() => {
    if (!scanId) return
    let cancelled = false
    const controller = new AbortController()
    api.scan(scanId, controller.signal).then(
      (result) => {
        if (cancelled) return
        setDetail(result)
        setState('ready')
      },
      (err: unknown) => {
        if (cancelled) return
        if (err instanceof ApiError && err.kind === 'aborted') return
        if (err instanceof ApiError && err.kind === 'not_found') {
          setState('notfound')
          return
        }
        setError(err instanceof ApiError ? err.message : 'The scan could not be read.')
        setState('error')
      },
    )
    return () => {
      cancelled = true
      controller.abort()
    }
  }, [scanId])

  return { state, detail, error }
}

export function ReportExportPage({ scanId }: { scanId?: number }) {
  const params = useParams<{ scanId: string }>()
  const id =
    scanId ?? (params.scanId && /^\d+$/.test(params.scanId) ? Number(params.scanId) : undefined)
  const { state, detail, error } = useScan(id)

  const [active, setActive] = useState<FormatId | null>(null)
  const [completed, setCompleted] = useState<FormatId[]>([])
  const [failure, setFailure] = useState<{ format: FormatId; message: string } | null>(null)

  const run = async (format: FormatId) => {
    if (!id || !detail) return
    setActive(format)
    setFailure(null)
    try {
      if (format === 'cbom' || format === 'sarif') {
        const { blob, filename } = await apiDownload(`/api/v1/scans/${id}/${format}`)
        saveBlob(filename ?? FORMATS.find((spec) => spec.id === format)!.filename(id), blob)
      } else if (format === 'json') {
        saveBlob(
          `piquachu-scan-${id}.json`,
          new Blob([JSON.stringify(detail, null, 2)], { type: 'application/json' }),
        )
      } else {
        saveBlob(
          `piquachu-findings-${id}.csv`,
          new Blob([findingsToCsv(detail)], { type: 'text/csv;charset=utf-8' }),
        )
      }
      setCompleted((previous) => (previous.includes(format) ? previous : [...previous, format]))
    } catch (err) {
      setFailure({
        format,
        message: err instanceof ApiError ? err.message : 'The export failed.',
      })
    } finally {
      setActive(null)
    }
  }

  if (!id) {
    return (
      <div className="mx-auto w-full max-w-[1100px] px-4 py-8 sm:px-6">
        <Panel>
          <EmptyState
            tone="error"
            title="A scan id is required"
            description="Exports belong to one stored scan."
            action={
              <Button size="sm" variant="primary" asChild>
                <Link to="/history">Scan history</Link>
              </Button>
            }
          />
        </Panel>
      </div>
    )
  }

  if (state === 'loading') {
    return (
      <div className="mx-auto w-full max-w-[1100px] px-4 py-8 sm:px-6">
        <p className="text-[13px] text-[var(--muted-foreground)]">Loading the stored scan…</p>
      </div>
    )
  }

  if (state === 'notfound' || state === 'error' || !detail) {
    return (
      <div className="mx-auto w-full max-w-[1100px] px-4 py-8 sm:px-6">
        <PageHeader eyebrow="Reports" title="Exports unavailable" meta={`scan #${id}`} />
        <Panel>
          <EmptyState
            tone="error"
            icon={<FileSearch className="size-4" aria-hidden="true" />}
            title={state === 'notfound' ? 'No stored scan with this id' : 'The scan could not be read'}
            description={state === 'notfound' ? 'It may belong to another tenant or may not exist.' : (error ?? 'The API returned an error.')}
            action={
              <Button size="sm" variant="primary" asChild>
                <Link to="/history">Scan history</Link>
              </Button>
            }
          />
        </Panel>
      </div>
    )
  }

  return (
    <div className="rise-in mx-auto w-full max-w-[1100px] px-4 py-8 sm:px-6 md:py-10">
      <PageHeader
        eyebrow="Reports"
        parent={{ to: `/results/${detail.scan_id}`, label: 'Results' }}
        title="Report export"
        meta={`scan #${detail.scan_id} · ${detail.filename ?? 'unnamed archive'} · ${formatTimestamp(detail.timestamp)}`}
        description="Each artifact is generated from the stored scan record. Downloading never re-scans the archive, and no export is reported as complete until the browser has the bytes."
      />

      {failure && (
        <Panel className="mb-4" eyebrow="Export failed" title="Nothing was saved">
          <p role="alert" className="text-[12.5px] text-[var(--danger)]">
            {failure.message}
          </p>
          <p className="mt-2 text-[11px] text-[var(--muted-foreground)]">
            {failure.format === 'sarif'
              ? 'The API validates SARIF before returning it; a failure here may mean the stored findings could not be serialized.'
              : 'Check the scan id and the API connection, then try again.'}
          </p>
          <Button size="sm" className="mt-3" onClick={() => void run(failure.format)}>
            Retry
          </Button>
        </Panel>
      )}

      <div className="grid gap-3 sm:grid-cols-2">
        {FORMATS.map((spec) => {
          const done = completed.includes(spec.id)
          const working = active === spec.id
          return (
            <Panel key={spec.id} className="flex flex-col">
              <div className="flex items-start justify-between gap-3">
                <div>
                  <p className="font-mono text-[10px] uppercase tracking-[0.12em] text-[var(--muted-foreground)]">
                    {spec.source === 'server' ? 'server artifact' : 'browser artifact'}
                  </p>
                  <h2 className="mt-1 text-[15px] font-medium">{spec.label}</h2>
                  <p className="mt-0.5 text-[11.5px] text-[var(--muted-foreground)]">{spec.detail}</p>
                </div>
                {done && <Badge tone="success">downloaded</Badge>}
              </div>

              <p className="mt-3 flex-1 text-[11.5px] leading-relaxed text-[var(--muted-foreground)]">
                {spec.note}
              </p>

              <div className="mt-3 flex items-center gap-2">
                <Button
                  size="sm"
                  variant={spec.id === 'cbom' ? 'primary' : 'outline'}
                  onClick={() => void run(spec.id)}
                  disabled={working || active !== null}
                >
                  <Download className="size-3.5" aria-hidden="true" />
                  {working ? 'Preparing…' : `Download ${spec.label}`}
                </Button>
                <span className="truncate font-mono text-[10px] text-[var(--muted-foreground)]" title={spec.filename(detail.scan_id)}>
                  {spec.filename(detail.scan_id)}
                </span>
              </div>
            </Panel>
          )
        })}
      </div>

      <Panel className="mt-4" eyebrow="Provenance" title="What this report is">
        <div className="grid gap-4 sm:grid-cols-2">
          <ul className="space-y-2 text-[12px] leading-relaxed text-[var(--muted-foreground)]">
            <li>
              <span className="text-[var(--foreground)]">Scope:</span>{' '}
              {detail.findings.length} stored finding(s) and the compliance matrix for scan #
              {detail.scan_id}.
            </li>
            <li>
              <span className="text-[var(--foreground)]">Standards:</span> lifecycle statements
              come from the reviewed registry, not from this scan.
            </li>
            <li>
              <span className="text-[var(--foreground)]">Not included:</span> source snippets in
              SARIF, absolute host paths, credentials, or key bytes.
            </li>
          </ul>
          <div className="flex items-start gap-2.5 border-t border-[var(--border)] pt-3 sm:border-l sm:border-t-0 sm:pl-4 sm:pt-0">
            <ShieldCheck className="mt-0.5 size-4 shrink-0 text-[var(--primary)]" aria-hidden="true" />
            <p className="text-[11.5px] leading-relaxed text-[var(--muted-foreground)]">
              A report is evidence from a static scan. It is not a formal NIST certification,
              auditor approval or proof of regulatory compliance.
            </p>
          </div>
        </div>
      </Panel>

      <div className="mt-5 flex flex-wrap gap-2">
        <Button size="sm" variant="secondary" asChild>
          <Link to={`/results/${detail.scan_id}/cbom`}>
            <FileJson className="size-3.5" aria-hidden="true" />
            Inspect the CBOM
          </Link>
        </Button>
        <Button size="sm" variant="ghost" asChild>
          <Link to={`/results/${detail.scan_id}/findings`}>Open findings</Link>
        </Button>
      </div>
    </div>
  )
}

export default ReportExportPage
